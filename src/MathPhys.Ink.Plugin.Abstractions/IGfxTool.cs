/// 极少是"再画一个"。自动切回去省一次点击，而且不打断节奏。
/// </para>
/// <para>
/// 判据不是"点了按钮"，而是<b>真的落成了对象</b>：误触（按下就抬）不会触发切换，
/// 否则老师想画个坐标系、手一抖，工具就自己跑掉了。
/// </para>
/// </remarks>
