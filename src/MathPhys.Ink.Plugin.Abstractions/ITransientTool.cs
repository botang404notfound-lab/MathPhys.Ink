namespace MathPhys.Ink.Plugins;

/// <summary>
/// "瞬态工具"标记接口（M7.5）：这个工具是<b>一条命令</b>，不是一种"模式"。
/// </summary>
/// <remarks>
/// 大多数工具是"模式"：选了笔就一直能写，选了橡皮就一直能擦，用户按按钮的意图是
/// "接下来用它"。但有些按钮的意图是<b>"就这一下"</b> —— 典型例子是
/// "打开 GeoGebra 演示面板"：面板关掉之后，用户手上该还是原来那支笔，
/// 而不是一个不知道该干什么的"GeoGebra 工具"（画布不响应笔，看起来就像卡死了）。
/// <para>
/// 宿主看到工具实现了这个接口，就会在它被激活后<b>立即把控制权交回激活前的工具</b>
/// （没有"之前"时回退到笔）。于是插件只需要写"我要做什么"，
/// 不用自己想办法切回去 —— 插件本来也没有切换工具的能力。
/// </para>
/// <para>
/// <b>为什么是可选接口而不是给 <see cref="ITool"/> 加成员</b>：加成员会改到所有已分发
/// 插件的编译产物所引用的类型契约，而加新接口不会 —— 老插件不认识它，行为一字不变。
/// 这与 <c>IGfxBoardAwareRenderer</c> 是同一套做法。
/// </para>
/// </remarks>
public interface ITransientTool
{
}
